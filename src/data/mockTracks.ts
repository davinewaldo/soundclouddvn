// Helper to generate consistent waveform bars
function generateWaveform(seed: number, count = 64): number[] {
  const bars: number[] = [];
  let prev = 40;
  for (let i = 0; i < count; i++) {
    const change = Math.sin(i * 0.28 + seed) * 35 + Math.cos(i * 0.15) * 20;
    prev = Math.max(12, Math.min(95, prev * 0.3 + (45 + change) * 0.7));
    bars.push(Math.round(prev));
  }
  return bars;
}

